"""Deterministic, stateful security-findings service (CKS coverage).

Provides findings across the four CKS layers — application, container,
node-cloud, kubernetes-cluster — seeded from a static, deterministic scan.
Every finding carries the full per-finding structure (Issue, Severity,
Evidence, Affected Resource, Root Cause, Recommended Solution, Auto/Approval
Required, Remediation Status, Verification Status) and is labelled SIMULATED
when generated by this in-process store rather than a live scanner.

Security invariant (unchanged): the LLM is advisory only. Diagnoses are
produced by the mock/configured LLM, but remediation decisions come from the
authoritative policy engine, and execution only ever mutates the in-process
simulated cluster (or the allow-listed live demo namespace).
"""

from __future__ import annotations

import threading
from datetime import timedelta
