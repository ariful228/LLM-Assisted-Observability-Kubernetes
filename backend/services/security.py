def _to_evidence(clues: list[str]) -> list[EvidenceItem]:
    source = "simulated-scan"
    return [
        EvidenceItem(category="security-scan", source=source, summary=clue, data={"simulated": True})
        for clue in clues
    ]


def _seed() -> None:
    global _seeded
    with _lock:
        if _seeded:
            return
        for spec in _seed_specs():
            finding = _hydrate(spec, source="simulated-scan")
            _run_pipeline_body(finding)
            _findings[finding.finding_id] = finding
        _seeded = True


