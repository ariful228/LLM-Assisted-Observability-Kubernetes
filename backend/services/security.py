def _hydrate(spec: dict[str, Any], source: str) -> SecurityFinding:
    now = chrono.now()
    fid = next_finding_id()
    decision = PolicyDecisionType.NO_ACTION
    status = FindingStatus.OPEN
    remediation_status = "not_started"
    verification_status = VerificationStatus.PENDING
    params = dict(spec.get("action_params") or {})

    f = SecurityFinding(
        finding_id=fid,
        title=spec["title"],
        issue=spec["issue"],
        severity=Severity(spec.get("severity", Severity.MEDIUM)),
        layer=SecurityLayer(spec.get("layer", SecurityLayer.APPLICATION)),
        status=status,
        domain=spec.get("domain", ""),
        evidence=_to_evidence(spec.get("evidence") or []),
        affected_resource=spec.get("affected_resource", ""),
        root_cause=spec.get("root_cause", ""),
        recommended_solution=spec.get("recommended_solution", ""),
        recommended_action=spec.get("recommended_action", ""),
        action_params=params,
        decision=decision,
        approval_required=False,
        remediation_status=remediation_status,
        verification_status=verification_status,
        simulated=True,
        source=source,
        detected_at=now,
        created_at=now,
        updated_at=now,
    )
    f.add_to_timeline("created", f"finding injected from {source}")
    return f


def _diagnose(finding: SecurityFinding) -> str:
    """Advisory diagnosis.

    Uses the configured LLM (mock = offline deterministic) purely for prose;
    the returned text is a *proposal* — the policy engine remains authoritative.
    """
    from backend.services.llm import get_llm

    try:
        text = get_llm().diagnose_finding(finding)
        if text:
            return str(text)
    except Exception:  # noqa: BLE001 — diagnosis must never block the finding
        pass
    return (
        f"{finding.title}: {finding.root_cause} — recommend {finding.recommended_solution} "
        f"(policy engine decides the actual remediation decision)."
    )


def _apply_safe_config(config: str, target: str, namespace: str) -> dict[str, Any]:
    """Simulated, fully in-process security config change (no live cluster)."""
    return kube.get_kube().apply_security_config(config, target, namespace)


def _remediate_body(finding: SecurityFinding) -> dict[str, Any]:
    params = dict(finding.action_params)
    action = finding.recommended_action
    if action == "restart_deployment":
        return kube.get_kube().restart_deployment(params.get("deployment", ""), params.get("namespace", "ai-observability-demo"))
    if action == "scale_deployment":
        return kube.get_kube().scale_deployment(params.get("deployment", ""), params.get("namespace", "ai-observability-demo"), int(params.get("desired_replicas", 2)))
    if action == "rollback_rbac":
        return kube.get_kube().rollback_rbac(params.get("binding_name", ""))
    if action == "renew_certificate":
        return kube.get_kube().renew_certificate(params.get("namespace", "ai-observability-demo"), "cert-demo-tls", "cert-demo.ai-observability-demo.svc")
    if action == "apply_security_config":
        return _apply_safe_config(params.get("config", ""), params.get("target", ""), params.get("namespace", "ai-observability-demo"))
    return {"action": action, "result": "no-op", "detail": "no safe remediation mapped for this action"}


def _verify_body(finding: SecurityFinding) -> list[dict[str, Any]]:
    """Deterministic verification checks for the finding's remediation."""
    params = dict(finding.action_params)
    action = finding.recommended_action
    ns = params.get("namespace", "ai-observability-demo")
    checks: list[dict[str, Any]] = []
    try:
        if action == "restart_deployment":
            dep = kube.get_kube().get_deployment(params.get("deployment", ""), ns)
            checks.append({"name": "available", "passed": dep.get("available", 0) == dep.get("replicas", 0) and dep.get("available", 0) > 0, "actual": dep.get("available"), "detail": "deployment available"})
        elif action == "scale_deployment":
            dep = kube.get_kube().get_deployment(params.get("deployment", ""), ns)
            checks.append({"name": "replicas", "passed": dep.get("replicas", 0) == int(params.get("desired_replicas", 0)), "actual": dep.get("replicas"), "detail": "deployment at desired replica count"})
        elif action == "rollback_rbac":
            gone = not any(b.get("name") == params.get("binding_name") for b in kube.get_kube().get_rbac())
            checks.append({"name": "binding_removed", "passed": gone, "detail": "suspicious binding removed"})
        elif action == "apply_security_config":
            ok = kube.get_kube().security_config_applied(params.get("config", ""), params.get("target", ""))
            checks.append({"name": f"config:{params.get('config')}", "passed": ok, "detail": "security config applied to target"})
        else:
            checks.append({"name": "remediated", "passed": True, "detail": "no-op — nothing to verify"})
    except Exception as exc:  # noqa: BLE001
        checks.append({"name": "verify_error", "passed": False, "detail": str(exc)})
    return checks


def _run_pipeline_body(finding: SecurityFinding) -> None:
    """Safe pipeline: detect -> diagnose (advisory LLM) -> policy -> auto/approval."""
    finding.status = FindingStatus.DETECTED
    finding.add_to_timeline("detected", f"detected via {finding.source}")

    diag = _diagnose(finding)
    finding.add_to_timeline("diagnosed", diag)

    decision = get_policy_engine().evaluate_finding(finding)
    finding.decision = decision.decision
    finding.add_to_timeline("policy_checked", f"{decision.rule_id}: {decision.reason}")

    if decision.decision == PolicyDecisionType.NO_ACTION or decision.decision == PolicyDecisionType.BLOCKED:
        finding.status = FindingStatus.OPEN if decision.decision == PolicyDecisionType.NO_ACTION else FindingStatus.OPEN
        finding.add_to_timeline("no_action", decision.reason)
        return

    finding.approval_required = decision.decision == PolicyDecisionType.APPROVAL_REQUIRED
    if decision.decision == PolicyDecisionType.AUTO:
        finding.status = FindingStatus.REMEDIATING
        finding.remediation_status = "in_progress"
        finding.add_to_timeline("remediating", f"auto remediation via {finding.recommended_action}")
        _finish_remediation(finding)
    else:
        finding.status = FindingStatus.AWAITING_APPROVAL
        finding.remediation_status = "not_started"
        finding.add_to_timeline("waiting_approval", "human approval required before remediation")


def _finish_remediation(finding: SecurityFinding) -> None:
    finding.status = FindingStatus.REMEDIATING
    finding.remediation_status = "in_progress"
    try:
        result = _remediate_body(finding)
        finding.add_to_timeline("remediated", f"{finding.recommended_action}: {result.get('result', result)}")
        finding.remediation_status = "complete"
        checks = _verify_body(finding)
        finding.verification_checks = checks
        passed = bool(checks) and all(c.get("passed") for c in checks)
        finding.verification_status = VerificationStatus.PASSED if passed else VerificationStatus.FAILED
        finding.status = FindingStatus.REMEDIATED if passed else FindingStatus.VERIFICATION_FAILED
        finding.add_to_timeline(
            "verified",
            f"verification {'PASSED' if passed else 'FAILED'}: {[c.get('name') for c in checks]}",
        )
    except Exception as exc:  # noqa: BLE001
        finding.add_to_timeline("remediation_error", str(exc))
        finding.status = FindingStatus.OPEN
        finding.remediation_status = "failed"
    finding.touch()


