def get_store():
    _seed()
    return _findings


def list_findings(
    layer: Optional[str] = None,
    status: Optional[str] = None,
    severity: Optional[str] = None,
    domain: Optional[str] = None,
    simulated_only: bool = True,
) -> list[SecurityFinding]:
    findings = sorted(get_store().values(), key=lambda f: f.detected_at, reverse=True)
    if layer:
        findings = [f for f in findings if f.layer.value == layer]
    if status:
        findings = [f for f in findings if f.status.value == status.upper()]
    if severity:
        findings = [f for f in findings if f.severity.value == severity]
    if domain:
        findings = [f for f in findings if f.domain.lower() == domain.lower()]
    if simulated_only:
        findings = [f for f in findings if f.simulated]
    return findings


def get_finding(finding_id: str) -> Optional[SecurityFinding]:
    return get_store().get(finding_id)


def stats() -> dict[str, Any]:
    findings = list(get_store().values())
    layers: dict[str, dict[str, Any]] = {}
    for layer in SecurityLayer:
        layers[layer.value] = {"total": 0, **{s.value: 0 for s in Severity}, "remediated": 0, "waiting": 0}
    by_severity = {s.value: 0 for s in Severity}
    by_status = {st.value: 0 for st in FindingStatus}
    for f in findings:
        layers[f.layer.value]["total"] += 1
        layers[f.layer.value][f.severity.value] += 1
        if f.verification_status == VerificationStatus.PASSED:
            layers[f.layer.value]["remediated"] += 1
        if f.status == FindingStatus.AWAITING_APPROVAL:
            layers[f.layer.value]["waiting"] += 1
        by_severity[f.severity.value] += 1
        by_status[f.status.value] += 1
    return {
        "total": len(findings),
        "simulated": len([f for f in findings if f.simulated]),
        "by_layer": layers,
        "by_severity": by_severity,
        "by_status": by_status,
        "domains": sorted({f.domain for f in findings if f.domain}),
    }


