def create_finding(req: SecurityFindingRequest, source: str = "test-lab") -> SecurityFinding:
    """Inject a new finding (Security Test Lab) and run the safe pipeline."""
    finding = _hydrate(
        {
            "title": req.title,
            "issue": req.issue,
            "severity": req.severity,
            "layer": req.layer,
            "domain": req.domain,
            "affected_resource": req.affected_resource,
            "root_cause": req.root_cause,
            "recommended_solution": req.recommended_solution,
            "recommended_action": req.recommended_action,
            "action_params": req.action_params,
            "evidence": [req.issue],
        },
        source=source,
    )
    with _lock:
        _run_pipeline_body(finding)
        _findings[finding.finding_id] = finding
    return finding


def decide_finding(finding_id: str, decision: str, approved_by: str = "webui-user", reason: str = "") -> SecurityFinding:
    finding = get_finding(finding_id)
    if finding is None:
        raise KeyError(finding_id)
    if finding.status != FindingStatus.AWAITING_APPROVAL:
        raise ValueError(f"finding {finding_id} is not waiting for approval (status={finding.status.value})")
    if decision == "reject":
        finding.status = FindingStatus.OPEN
        finding.remediation_status = "not_started"
        finding.add_to_timeline("rejected", reason or f"rejected by {approved_by}")
        finding.touch()
        return finding
    finding.add_to_timeline("approved", f"approved by {approved_by}: {reason or 'proceed'}")
    _finish_remediation(finding)
    return finding


