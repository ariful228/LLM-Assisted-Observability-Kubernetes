def lab_scenarios() -> list[dict[str, Any]]:
    return [
        {
            "key": key,
            "layer": SecurityLayer(S["layer"]).value if isinstance(S["layer"], SecurityLayer) else S["layer"],
            "title": S["title"],
            "decision_hint": "AUTO" if S["layer"] == SecurityLayer.APPLICATION else "APPROVAL_REQUIRED",
        }
        for key, S in LAB_SCENARIOS.items()
    ]


def run_lab(key: str) -> SecurityFinding:
    if key not in LAB_SCENARIOS:
        raise KeyError(f"unknown lab scenario {key!r}")
    spec = LAB_SCENARIOS[key]
    req = SecurityFindingRequest(
        title=spec["title"],
        issue=spec["issue"],
        severity=spec["severity"] if isinstance(spec["severity"], Severity) else Severity(spec["severity"]),
        layer=spec["layer"] if isinstance(spec["layer"], SecurityLayer) else SecurityLayer(spec["layer"]),
        domain=spec.get("domain", ""),
        affected_resource=spec.get("affected_resource", ""),
        root_cause=spec.get("root_cause", ""),
        recommended_solution=spec.get("recommended_solution", ""),
        recommended_action=spec.get("recommended_action", ""),
        action_params=spec.get("action_params", {}),
    )
    return create_finding(req, source=f"test-lab:{key}")